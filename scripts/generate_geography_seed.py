#!/usr/bin/env python3
"""Convert the cited IEBC hierarchy CSV into deterministic, idempotent SQL."""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path


def sql(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def display_name(value: str) -> str:
    return value.strip().title().replace("/", " / ").replace("  ", " ")


def slug(value: str) -> str:
    return re.sub(r"(^-|-$)", "", re.sub(r"[^a-z0-9]+", "-", value.lower()))


def load(path: Path) -> tuple[dict[int, str], dict[int, tuple[int, str]], list[tuple[int, int, str]]]:
    counties: dict[int, str] = {}
    constituencies: dict[int, tuple[int, str]] = {}
    wards: list[tuple[int, int, str]] = []
    with path.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            county_code = int(row["COUNTY ID"])
            raw_constituency_code = row["CONSTITUENCY ID"].strip()
            # The source CSV has one known transcription gap: all five Baringo
            # North rows are marked #N/A between constituency codes 157 and 159.
            constituency_code = 158 if raw_constituency_code == "#N/A" and row["CONSTITUENCY NAME"].strip() == "BARINGO  NORTH" else int(raw_constituency_code)
            ward_code = int(row["WARD ID"])
            counties[county_code] = display_name(row["COUNTY NAME"])
            constituencies[constituency_code] = (county_code, display_name(row["CONSTITUENCY NAME"]))
            wards.append((ward_code, constituency_code, display_name(row["WARD NAME"])))
    expected = (47, 290, 1450)
    actual = (len(counties), len(constituencies), len(wards))
    if actual != expected:
        raise ValueError(f"Geography count mismatch: expected {expected}, got {actual}")
    return counties, constituencies, wards


def render(source: Path) -> str:
    counties, constituencies, wards = load(source)
    lines = [
        "\\set ON_ERROR_STOP on",
        "",
        "-- Source: IEBC hierarchy transcribed by pkiage/data-Kenya-Counties-Constituencies-Wards.",
        "-- Generated by scripts/generate_geography_seed.py; 47 counties, 290 constituencies, 1,450 wards.",
        "BEGIN;",
        "",
        "INSERT INTO counties (id, code, name, slug) VALUES",
    ]
    county_values = [
        f"    (md5('county:{code}')::uuid, {code}, {sql(name)}, {sql(slug(name))})"
        for code, name in sorted(counties.items())
    ]
    lines.append(",\n".join(county_values))
    lines.extend([
        "ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, slug = EXCLUDED.slug;",
        "",
        "INSERT INTO constituencies (id, county_id, code, name, slug) VALUES",
    ])
    constituency_values = [
        f"    (md5('constituency:{code}')::uuid, md5('county:{county_code}')::uuid, {code}, {sql(name)}, {sql(slug(name))})"
        for code, (county_code, name) in sorted(constituencies.items())
    ]
    lines.append(",\n".join(constituency_values))
    lines.extend([
        "ON CONFLICT (code) DO UPDATE SET county_id = EXCLUDED.county_id, name = EXCLUDED.name, slug = EXCLUDED.slug;",
        "",
        "INSERT INTO wards (id, constituency_id, code, name, slug) VALUES",
    ])
    ward_values = [
        f"    (md5('ward:{code}')::uuid, md5('constituency:{constituency_code}')::uuid, {code}, {sql(name)}, {sql(slug(name))})"
        for code, constituency_code, name in sorted(wards)
    ]
    lines.append(",\n".join(ward_values))
    lines.extend([
        "ON CONFLICT (code) DO UPDATE SET constituency_id = EXCLUDED.constituency_id, name = EXCLUDED.name, slug = EXCLUDED.slug;",
        "",
        "DO $$",
        "DECLARE county_count integer; constituency_count integer; ward_count integer;",
        "BEGIN",
        "    SELECT count(*) INTO county_count FROM counties;",
        "    SELECT count(*) INTO constituency_count FROM constituencies;",
        "    SELECT count(*) INTO ward_count FROM wards;",
        "    IF county_count <> 47 OR constituency_count <> 290 OR ward_count <> 1450 THEN",
        "        RAISE EXCEPTION 'Geography validation failed: % counties, % constituencies, % wards', county_count, constituency_count, ward_count;",
        "    END IF;",
        "END",
        "$$;",
        "",
        "SELECT set_config('app.tenant_id', '10000000-0000-4000-8000-000000000001', true);",
        "",
        "WITH demo_mentions(idx, source, author_handle, body, lang, sheng, engagement, county_code, constituency_code, ward_code, axis, score) AS (",
        "    VALUES",
        "    (1, 'x', '@nairobipulse', 'Transport costs are rising but the new commuter route is helping.', 'en', false, 384, 47, 289, 1439, 'economy', -0.28),",
        "    (2, 'tiktok', '@mtaawatch', 'Manze barabara ya Nakuru iko poa leo, progress ni real.', 'sheng', true, 821, 32, 176, 876, 'infrastructure', 0.61),",
        "    (3, 'facebook', 'Kisumu Health Forum', 'Hospital wait times have improved this week, hongera wahudumu.', 'sw', false, 246, 42, 240, 1199, 'healthcare', 0.67),",
        "    (4, 'news', 'Coast Daily Desk', 'Mombasa youth employment programme receives 2,000 applications.', 'en', false, 190, 1, 6, 26, 'youth_employment', 0.31),",
        "    (5, 'x', '@kiamburesident', 'Water interruptions in Kiambu need a clear county response.', 'en', false, 512, 22, 117, 582, 'infrastructure', -0.52),",
        "    (6, 'facebook', 'Uasin Gishu Farmers', 'Fertilizer delivery arrived on time and farmers expect a stronger season.', 'en', false, 146, 27, 144, 719, 'agriculture', 0.58),",
        "    (7, 'tiktok', '@mombasani', 'Bei ya chakula ni ghali sana, wasee wanataka majibu sasa.', 'sheng', true, 934, 1, 3, 9, 'economy', -0.74),",
        "    (8, 'news', 'Central Desk', 'Kirinyaga leaders open a new produce aggregation centre.', 'en', false, 88, 20, 103, 512, 'local_leadership', 0.46)",
        "), inserted AS (",
        "    INSERT INTO mentions (tenant_id, county_id, constituency_id, ward_id, source, external_id, author_handle, text, language, sheng_detected, engagement_count, collected_at, raw_payload)",
        "    SELECT '10000000-0000-4000-8000-000000000001'::uuid, c.id, co.id, w.id, d.source, 'seed-' || d.idx, d.author_handle, d.body, d.lang, d.sheng, d.engagement, now() - (d.idx || ' minutes')::interval, '{\"seed\":true}'::jsonb",
        "    FROM demo_mentions d",
        "    JOIN counties c ON c.code = d.county_code",
        "    JOIN constituencies co ON co.code = d.constituency_code AND co.county_id = c.id",
        "    JOIN wards w ON w.code = d.ward_code AND w.constituency_id = co.id",
        "    ON CONFLICT (tenant_id, source, external_id) WHERE external_id IS NOT NULL DO UPDATE SET county_id = EXCLUDED.county_id, constituency_id = EXCLUDED.constituency_id, ward_id = EXCLUDED.ward_id, engagement_count = EXCLUDED.engagement_count",
        "    RETURNING id, external_id",
        ")",
        "INSERT INTO sentiment_scores (tenant_id, mention_id, issue_axis, score, confidence, model_version)",
        "SELECT '10000000-0000-4000-8000-000000000001'::uuid, i.id, d.axis, d.score, 0.91, 'seed-baseline-1.0'",
        "FROM inserted i JOIN demo_mentions d ON i.external_id = 'seed-' || d.idx",
        "ON CONFLICT (mention_id, issue_axis) DO UPDATE SET score = EXCLUDED.score, confidence = EXCLUDED.confidence;",
        "",
        "INSERT INTO alerts (id, tenant_id, county_id, severity, category, title, narrative, status, playbook)",
        "SELECT '40000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001', c.id, 3, 'coordinated_narrative',",
        "       'Cost-of-living narrative accelerating',",
        "       'A multilingual negative narrative is accelerating across public channels in Mombasa.', 'open',",
        "       '[{\"minute\":0,\"action\":\"Verify source cluster\",\"owner\":\"Sentry analyst\"},{\"minute\":10,\"action\":\"Issue bilingual holding line\",\"owner\":\"Communications\"},{\"minute\":20,\"action\":\"Launch CATI pulse check\",\"owner\":\"Voice supervisor\"}]'::jsonb",
        "FROM counties c WHERE c.code = 1",
        "ON CONFLICT (id) DO UPDATE SET narrative = EXCLUDED.narrative, playbook = EXCLUDED.playbook;",
        "",
        "COMMIT;",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_geography_seed.py INPUT.csv OUTPUT.sql")
    source, output = map(Path, sys.argv[1:])
    output.write_text(render(source), encoding="utf-8")


if __name__ == "__main__":
    main()

